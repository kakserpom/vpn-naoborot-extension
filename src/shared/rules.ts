/**
 * Правила выборочного проксирования: разбор доменов, сопоставление с хостом
 * и генерация PAC-скрипта для chrome.proxy.
 */

import { API_HOST } from "./constants";
import { DEFAULT_PROXY_DOMAINS } from "./defaults";
import type { ProxyRule, ProxyRulesSettings, ProxyServer } from "./types";

/**
 * Настройки по умолчанию: включён режим «только из списка»,
 * в списке — популярные российские сервисы (см. defaults.ts).
 */
export const DEFAULT_RULES: ProxyRulesSettings = {
  mode: "listed",
  rules: DEFAULT_PROXY_DOMAINS.map((domain) => ({ domain, action: "proxy" as const })),
};

const DOMAIN_RE = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;
/** Домен может содержать Unicode-буквы (IDN) — их вид приводим к punycode. */
const UNICODE_DOMAIN_RE = /^[^\s./:@?#]+(\.[^\s./:@?#]+)+$/;

/**
 * Приводит пользовательский ввод к домену: убирает схему, путь, порт,
 * ведущий «*.» и лишние пробелы. Возвращает `null`, если это не домен.
 * Кириллические домены остаются в читаемом виде — в PAC они попадут
 * уже в punycode (см. `toAsciiDomain`).
 */
export function normalizeDomain(input: string): string | null {
  if (!input) return null;
  let value = input.trim().toLowerCase();
  if (!value) return null;

  value = value.replace(/^[a-z][a-z0-9+.-]*:\/\//, ""); // scheme
  value = value.split("/")[0]; // path
  value = value.split("?")[0];
  value = value.split("#")[0];
  value = value.replace(/^[^@]*@/, ""); // user:pass@
  value = value.replace(/:\d+$/, ""); // port
  value = value.replace(/^\*\./, ""); // wildcard prefix
  value = value.replace(/\.$/, ""); // trailing dot

  if (!UNICODE_DOMAIN_RE.test(value)) return null;
  // домен должен корректно кодироваться в ASCII
  if (!DOMAIN_RE.test(toAsciiDomain(value))) return null;
  return value;
}

/** Совпадает ли хост с доменом (сам домен или его поддомен). */
export function matchesHost(host: string, domain: string): boolean {
  const h = host.toLowerCase();
  const d = domain.toLowerCase();
  if (!h || !d) return false;
  return h === d || h.endsWith(`.${d}`);
}

/** Убирает дубликаты правил (по домену оставляем первое). */
export function dedupeRules(rules: ProxyRule[]): ProxyRule[] {
  const seen = new Set<string>();
  const result: ProxyRule[] = [];
  for (const rule of rules) {
    const domain = normalizeDomain(rule.domain);
    if (!domain || seen.has(domain)) continue;
    seen.add(domain);
    result.push({ domain, action: rule.action });
  }
  return result;
}

/**
 * Переводит домен в ASCII (Punycode).
 * Chrome принимает в `pacScript.data` только ASCII-строки, а PAC-движок
 * передаёт хоста тоже в punycode — поэтому кириллические домены надо кодировать.
 */
export function toAsciiDomain(domain: string): string {
  try {
    return new URL(`http://${domain}`).hostname.toLowerCase();
  } catch {
    return domain.toLowerCase();
  }
}

/**
 * Собирает PAC-скрипт.
 *
 * Логика:
 *  1. Хост API всегда идёт напрямую — иначе запросы к API зациклятся.
 *  2. Правила из списка проверяются по порядку; первое совпадение решает.
 *  3. Если совпадений нет — применяется режим: `all` (всё через прокси)
 *     или `listed` (только сайты из списка).
 */
export function buildPacScript(params: {
  proxies: ProxyServer[];
  mode: ProxyRulesSettings["mode"];
  rules: ProxyRule[];
}): string {
  const { proxies, mode, rules } = params;

  const proxyList = [...new Set(proxies.map((p) => `${p.host}:${p.port}`))];
  const proxyString = proxyList.map((p) => `PROXY ${p}`).join("; ");

  const ruleList = dedupeRules(rules)
    .map((rule) => `["${toAsciiDomain(rule.domain)}",${rule.action === "proxy" ? 1 : 0}]`)
    .join(",");

  const script = `// Generated by VPN Naoborot. Do not edit manually.
var PROXY_LIST = ${JSON.stringify(proxyString)};
var API_HOST = ${JSON.stringify(API_HOST)};
var MODE = ${JSON.stringify(mode)};
var RULES = [${ruleList}];

function FindProxyForURL(url, host) {
  host = (host || "").toLowerCase();

  // API requests always go directly, otherwise they would loop through the proxy
  if (host === API_HOST || dnsDomainIs(host, API_HOST)) return "DIRECT";

  for (var i = 0; i < RULES.length; i++) {
    var domain = RULES[i][0];
    if (host === domain || dnsDomainIs(host, domain)) {
      return RULES[i][1] ? PROXY_LIST : "DIRECT";
    }
  }

  if (MODE === "listed") return "DIRECT";
  return PROXY_LIST;
}
`;

  // Chrome принимает в pacScript.data только ASCII
  return /[^\x00-\x7F]/.test(script)
    ? script.replace(/[^\x00-\x7F]/g, "")
    : script;
}
